#!/usr/bin/env node
/**
 * #186: prebuild the pack install lint (plugins/sdk/pack-install-lint.ts and what it imports) into
 * the plain ESM file web/scripts/pack-install-lint.built.mjs, so bundle-pack-entry.mjs runs it
 * in-process and installing a pack needs no TypeScript runner.
 *
 *   node scripts/build-pack-install-lint.mjs          write the file if it differs (web/ `prepare`)
 *   node scripts/build-pack-install-lint.mjs --check  exit 1 if the committed file is stale
 *
 * The built file is committed (a pull without a reinstall, or an `--ignore-scripts` install, still has
 * a correct one) and `prepare` regenerates it on every `pnpm install` in web/. Without esbuild (e.g.
 * `pnpm install --prod`) `prepare` keeps the committed file and exits 0; bundle-pack-entry.mjs refuses
 * the install (exit 3) if that file is missing or doesn't match the sources.
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { BUILT_LINT_FILE, inputsDigest } from "./pack-install-lint-stamp.mjs";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
export const LINT_ENTRY = "plugins/sdk/pack-install-lint.ts";
export const BUILT_LINT_PATH = path.join(scriptsDir, BUILT_LINT_FILE);

const HEADER = [
  `// GENERATED by web/scripts/build-pack-install-lint.mjs from ${LINT_ENTRY} (#186). Do not edit.`,
  "// `pnpm install` in web/ regenerates it (the `prepare` script); pack-install-lint-prebuilt.test.ts",
  "// fails when it doesn't match a fresh build of the sources.",
  "",
].join("\n");

/** The built file's text for the sources under `repoRoot`, deterministic for one esbuild version. */
export async function buildPackInstallLint({ repoRoot = path.resolve(scriptsDir, "../.."), esbuild } = {}) {
  const eb = esbuild ?? (await import("esbuild"));
  const result = await eb.build({
    absWorkingDir: repoRoot,
    entryPoints: [LINT_ENTRY],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    write: false,
    metafile: true,
    legalComments: "none",
    charset: "utf8",
    // Paths as the checkout lays them out (a linked plugins/sdk still reads "plugins/sdk/…"), so the
    // output and its stamp don't depend on where the files really live.
    preserveSymlinks: true,
    logLevel: "silent",
  });
  const inputs = Object.keys(result.metafile.inputs).map((p) => p.replace(/\\/g, "/")).sort();
  const stamp = { entry: LINT_ENTRY, inputs, sha256: inputsDigest(repoRoot, inputs) };
  return `${HEADER}${result.outputFiles[0].text}export const PACK_INSTALL_LINT_BUILD = ${JSON.stringify(stamp, null, 2)};\n`;
}

async function main() {
  const check = process.argv.includes("--check");
  let esbuild;
  try {
    esbuild = await import("esbuild");
  } catch (err) {
    const msg = `esbuild not importable (${String(err?.code || err?.message || err)})`;
    if (check) {
      console.error(`${msg}; can't check ${BUILT_LINT_FILE}`);
      process.exit(1);
    }
    console.warn(`${msg}: keeping the committed web/scripts/${BUILT_LINT_FILE}`);
    return;
  }
  const text = await buildPackInstallLint({ esbuild });
  const current = fs.existsSync(BUILT_LINT_PATH) ? fs.readFileSync(BUILT_LINT_PATH, "utf8") : null;
  if (current === text) return;
  if (check) {
    console.error(`web/scripts/${BUILT_LINT_FILE} is ${current === null ? "missing" : "stale"}; run \`pnpm install\` in web/`);
    process.exit(1);
  }
  fs.writeFileSync(BUILT_LINT_PATH, text);
  console.log(`wrote web/scripts/${BUILT_LINT_FILE}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await main();
}
